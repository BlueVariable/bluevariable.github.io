#!/usr/bin/env node
/* Generates the procedural torn-paper masks used in assets/css/site.css.
   Run `node _tools/tear-masks.js` and paste the output over the block between
   the "generated by _tools/tear-masks.js" markers. No dependencies.

   Each mask is a tiny SVG: a rect filled with a gradient (opaque paper -> torn
   edge), plus an feTurbulence speckle that is added to the gradient and hard-
   thresholded, which gives the dry-brush grit of the Canva tear. Three frames
   are rendered per direction; they share the speckle but each is nudged by a
   different low-frequency displacement, and site.css steps through them for a
   subtle line boil. The SVGs have no intrinsic size, so `mask-size: 100% <h>`
   lays each one across the full width without repeating (no seams). */

const GRAIN = { freq: [0.3, 0.45], octaves: 3, seed: 3, k4: -0.55, slope: 30, intercept: -14.5 };
const BOIL = { freq: [0.03, 0.05], scale: 3, seeds: [1, 2, 3] };

/* stop offsets are fractions of the band; alpha ~.57 gives ~70% speckle coverage */
const PROFILE = {
  bottom: [[0.7, 1], [0.78, 0.58], [0.9, 0.56], [1, 0.3]],   /* only the last 10px of the 45px band show */
  top:    [[0.4, 1], [0.52, 0.6], [0.92, 0.57], [1, 0.25]],  /* the first 22px of the 45px band show */
};

const DIRS = {
  b: { grad: "x1='0' y1='0' x2='0' y2='100%'", profile: 'bottom', swap: false },
  t: { grad: "x1='0' y1='100%' x2='0' y2='0'", profile: 'top', swap: false },
  l: { grad: "x1='100%' y1='0' x2='0' y2='0'", profile: 'top', swap: true },
  r: { grad: "x1='0' y1='0' x2='100%' y2='0'", profile: 'top', swap: true },
};

const freq = (f, swap) => (swap ? [f[1], f[0]] : f).join(' ');

function svg(dir, frame) {
  const d = DIRS[dir];
  const stops = PROFILE[d.profile].map(([o, a]) => `<stop offset='${o}' stop-color='#fff' stop-opacity='${a}'/>`).join('');
  const rect = d.swap ? "x='-10' y='-5%' width='150%' height='110%'" : "x='-5%' y='-10' width='110%' height='150%'";
  return `<svg xmlns='http://www.w3.org/2000/svg' width='100%' height='100%'>` +
    `<defs><linearGradient id='g' gradientUnits='userSpaceOnUse' ${d.grad}>${stops}</linearGradient>` +
    `<filter id='f' x='0' y='0' width='100%' height='100%'>` +
    `<feTurbulence type='fractalNoise' baseFrequency='${freq(GRAIN.freq, d.swap)}' numOctaves='${GRAIN.octaves}' seed='${GRAIN.seed}' result='n'/>` +
    `<feComposite in='SourceGraphic' in2='n' operator='arithmetic' k2='1' k3='1' k4='${GRAIN.k4}'/>` +
    `<feComponentTransfer result='m'><feFuncA type='linear' slope='${GRAIN.slope}' intercept='${GRAIN.intercept}'/></feComponentTransfer>` +
    `<feTurbulence type='fractalNoise' baseFrequency='${freq(BOIL.freq, d.swap)}' numOctaves='1' seed='${BOIL.seeds[frame]}' result='w'/>` +
    `<feDisplacementMap in='m' in2='w' scale='${BOIL.scale}' xChannelSelector='R' yChannelSelector='G'/>` +
    `</filter></defs><rect ${rect} fill='url(#g)' filter='url(#f)'/></svg>`;
}

const uri = (s) => `url("data:image/svg+xml,${s.replace(/%/g, '%25').replace(/#/g, '%23')}")`;

let out = '';
for (const dir of Object.keys(DIRS)) {
  for (let k = 0; k < BOIL.seeds.length; k++) out += `  --tear-${dir}${k + 1}: ${uri(svg(dir, k))};\n`;
}
process.stdout.write(out);
